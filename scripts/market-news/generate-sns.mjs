// Review step helper: ChatGPT primary, Claude self-review fallback.
async function reviewWithChatGPT(prompt) {
  try {
    const r = await chatgpt([{ role: 'user', content: prompt }], { max_tokens: 8000 });
    return { issues: chatgptJson(r), reviewer: `chatgpt:${r._modelUsed}` };
  } catch (e) {
    console.warn(`  [!] ChatGPT review failed (${e.message?.slice(0, 80)}), falling back to Claude`);
    const r = await claude([{ role: 'user', content: prompt }], { max_tokens: 4000 });
    return { issues: jsonOf(r), reviewer: `claude:${r._modelUsed}` };
  }
}

function arg(name, fallback) {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : fallback;
}

